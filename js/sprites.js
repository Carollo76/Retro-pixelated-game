function generateBossSprite(color1, color2, accentColor) {
    // Generate a 48x48 boss sprite
    const sprite = [];
    for (let y = 0; y < 48; y++) {
        const row = [];
        for (let x = 0; x < 48; x++) {
            // Create symmetrical boss shape
            const cx = Math.abs(x - 24);
            const cy = y;

            // Main body
            if (cy >= 8 && cy <= 40 && cx <= 20 - Math.abs(cy - 24) / 2) {
                if (cy >= 16 && cy <= 32 && cx <= 8) {
                    row.push(accentColor); // Core
                } else if ((cy === 12 || cy === 36) && cx >= 6 && cx <= 10) {
                    row.push(12); // Lights
                } else {
                    row.push(color1);
                }
            }
            // Wings
            else if (cy >= 16 && cy <= 32 && cx >= 16 && cx <= 22) {
                row.push(color2);
            }
            // Cannons
            else if (cy >= 38 && cy <= 44 && (cx >= 8 && cx <= 12)) {
                row.push(color1);
            }
            else {
                row.push(0);
            }
        }
        sprite.push(row);
    }
    return sprite;
}

// Sprite rendering utility
class SpriteRenderer {
    constructor(ctx) {
        this.ctx = ctx;
        this.spriteCache = new Map();
    }

    drawSprite(sprite, x, y, scale = 1) {
        const cacheKey = `${JSON.stringify(sprite)}_${scale}`;

        if (!this.spriteCache.has(cacheKey)) {
            // Create cached canvas for this sprite
            const canvas = document.createElement('canvas');
            canvas.width = sprite[0].length * scale;
            canvas.height = sprite.length * scale;
            const tempCtx = canvas.getContext('2d');

            for (let row = 0; row < sprite.length; row++) {
                for (let col = 0; col < sprite[row].length; col++) {
                    const colorIndex = sprite[row][col];
                    if (colorIndex !== 0) {
                        tempCtx.fillStyle = COLORS[colorIndex] || '#ff00ff';
                        tempCtx.fillRect(col * scale, row * scale, scale, scale);
                    }
                }
            }

            this.spriteCache.set(cacheKey, canvas);
        }

        this.ctx.drawImage(this.spriteCache.get(cacheKey), Math.floor(x), Math.floor(y));
    }

    clearCache() {
        this.spriteCache.clear();
    }
}

